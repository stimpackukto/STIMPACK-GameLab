<h2>1. 이용규칙</h2>
<p>상대방 비방·욕설·혐오 표현, 반복 광고, 개인정보 공개, 시험 부정행위 조장, 허가받지 않은 유료 교재·강의 원문 업로드는 금지됩니다. 본인이 공유할 권리가 있는 파일과 링크만 게시하세요. 문제가 있는 글은 게시글 내 '신고'를 이용할 수 있습니다. 작성자는 자기 글·댓글을 삭제할 수 있고, 관리자는 규칙 위반 콘텐츠를 삭제할 수 있습니다.</p>
<h2>2. 로그인 및 개인정보</h2>
<p>읽기는 로그인이 필요하지 않습니다. 글·댓글·자료 등록은 STIMPACK GAME LAB의 Google OAuth 로그인으로 인증합니다. 게시판 DB에는 Google 이메일이나 실명을 저장하지 않습니다. Google 계정 고유 사용자 식별자의 SHA-256 해시로 작성자를 구분하고 화면에는 '학습자-XXXXXX' 별칭을 표시합니다. Google OAuth 로그인 세션에는 Google 프로필 정보가 저장될 수 있습니다. 일반 웹 서버 접속 로그에는 IP 주소와 접속시간 등이 포함될 수 있습니다.</p>
<h2>3. 보관 및 삭제</h2>
<p>게시글·댓글·첨부파일·신고·차단 정보는 운영 서버의 DB와 비공개 파일 저장소에 기록됩니다. 글 삭제 시 일반 화면에서 숨기고 업로드 파일을 삭제합니다. 보존 기간과 백업 및 개인정보 열람·삭제 요청에 대한 응대는 서버 운영 정책 및 관계 법령에 따릅니다.</p>
